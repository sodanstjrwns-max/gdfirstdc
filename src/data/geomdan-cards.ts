export const geomdanCard = (path: string) => GEOMDAN_CARDS.find((c) => c.path === path)

/** 카드 이미지 경로 — og(1200×630 jpg), body(1200×800 webp), card(600×600 webp) */
export function geomdanCardImg(c: GeomdanCard, kind: 'og' | 'body' | 'card'): string {
  const base = `/static/images/cards/${c.img}`
  return kind === 'og' ? `${base}-1200x630.jpg` : kind === 'body' ? `${base}-1200.webp` : `${base}-600.webp`
}

/** 홈·허브 ItemList JSON-LD — 화면 카드 그리드와 1:1 (같은 순서·이름·url·image) */
export function geomdanItemListJsonLd(id: string): object {
  return {
    '@context': 'https://schema.org',
    '@type': 'ItemList',
    '@id': id,
    name: '검단 진료별 안내',
    numberOfItems: GEOMDAN_CARDS.length,
    itemListElement: GEOMDAN_CARDS.map((c, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: c.name,
      url: `${CLINIC.siteUrl}${c.path}`,
      image: `${CLINIC.siteUrl}${geomdanCardImg(c, 'og')}`,
    })),
  }
}

/** 진료 페이지(/treatments/:slug) og 1200×630 — 검단 카드가 있는 진료는 같은 대표 사진, 나머지는 원내 실사 파생본 */
const TX_OG_EXTRA: Record<string, string> = {
  aesthetic: '/static/images/og/tx-aesthetic-1200x630.jpg',
  gum: '/static/images/og/tx-gum-1200x630.jpg',
  prosthetics: '/static/images/og/tx-prosthetics-1200x630.jpg',
  botox: '/static/images/og/tx-botox-1200x630.jpg',
}
export function txOgImage(slug: string): string {
  const card = GEOMDAN_CARDS.find((c) => c.tx === slug)
  if (card) return geomdanCardImg(card, 'og')
  return TX_OG_EXTRA[slug] || '/static/images/og_default.jpg'
}
